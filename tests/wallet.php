function wallet_order() {
    global $ref;
    $o = reset_order();
    $o->payment_method = 'jccg_wallet';
    $o->meta['_jccg_attempts'][$ref]['instrument'] = 'wallet';
    return $o;
}
function wallet_signed(array $changes = array()) {
    return signed(array_merge(array('pp_TxnType'=>'MWALLET'), $changes));
}
